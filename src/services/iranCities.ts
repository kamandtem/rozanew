/**
 * جست‌وجوی «شروع‌شونده با ابتدای کلمه» ارجحیت دارد، بعد شامل‌بودن در هر جای
 * نام؛ همین ترتیب رایج‌ترین رفتار اتوکامپلیت آدرس در اپ‌های موبایل است.
 */
export function searchIranCities(query: string, limit = 6): string[] {
  const trimmed = query.trim();
  if (!trimmed) return [];
  const startsWith = IRAN_CITIES.filter((city) => city.startsWith(trimmed));
  const includes = IRAN_CITIES.filter((city) => !city.startsWith(trimmed) && city.includes(trimmed));
  return [...startsWith, ...includes].slice(0, limit);
}
