/**
 * نرمال‌سازی متن فارسی. فایل برگ (leaf) — هیچ import ندارد، پس هر لایه‌ای
 * می‌تواند از آن بخواند بدون ریسک وابستگی حلقه‌ای.
 *
 * بدون این، «ي» عربی، «ك» عربی، نیم‌فاصله، اعراب و فاصله‌های اضافه باعث
 * می‌شدند نام ترکیبی که کاربر دستی نوشته با دیتابیس جور نشود — همان
 * چیزی که باعث می‌شد حساسیت‌های انگلیسی‌نوشته یا فارسیِ با املای دیگر
 * از قاعده‌ها جا بمانند.
 */

export function normalizeFa(input: string): string {
  return (input || '')
    .replace(/[\u064A\u0649]/g, '\u06CC') // ي / ى  →  ی
    .replace(/\u0643/g, '\u06A9') // ك  →  ک
    .replace(/[\u200B-\u200F\u202A-\u202E\uFEFF]/g, '') // نیم‌فاصله و کاراکترهای جهت‌دهی
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]/g, '') // اعراب
    .replace(/[\u06F0-\u06F9]/g, (digit) => String(digit.charCodeAt(0) - 0x06f0))
    .replace(/[\u0660-\u0669]/g, (digit) => String(digit.charCodeAt(0) - 0x0660))
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}
