/**
 * فهرست برندهای شناخته‌شده مراقبت پوست/آرایشی که در ایران رایج‌اند، برای
 * تکمیل خودکار فیلد «برند» در فرم ثبت محصول.
 *
 * کاملاً آفلاین و استاتیک است (هم‌راستا با قول حریم خصوصی اپ)، درست مثل
 * IRAN_CITIES. لیست کامل نیست — فقط پرکاربردترین برندهای ایرانی و
 * بین‌المللیِ در دسترس در داروخانه/فروشگاه‌های ایران. کاربر همیشه می‌تواند
 * برند دیگری هم تایپ کند؛ چیزی قفل نمی‌شود.
 */

export const KNOWN_BRANDS: string[] = [
  // برندهای ایرانی
  'سینره', 'این‌لی', 'مای', 'آردن', 'هیدرودرم', 'سریتا', 'کالیستا', 'سی‌گل', 'لیلاک',
  // برندهای مراقبت پوست بین‌المللی رایج در داروخانه‌های ایران
  'لاروش‌پوزای', 'بایودرما', 'ویشی', 'اوسرین', 'سیتافیل', 'نیتروژینا', 'نیوآ',
  'آون', 'اوریاژ', 'دوکری', 'سبامد', 'فیزیوژل', 'CeraVe', 'د اردینری',
  'کوزارکس', 'سام بای می', 'اینیس‌فری',
  // برندهای آرایشی رایج
  'لورآل', 'میبلین', 'گلدن رز', 'کلینیک',
];

/**
 * جست‌وجوی «شروع‌شونده با ابتدای کلمه» ارجحیت دارد، بعد شامل‌بودن در هر جای
 * نام — همان رفتار searchIranCities.
 */
export function searchKnownBrands(query: string, limit = 6): string[] {
  const trimmed = query.trim();
  if (!trimmed) return [];
  const startsWith = KNOWN_BRANDS.filter((brand) => brand.startsWith(trimmed));
  const includes = KNOWN_BRANDS.filter((brand) => !brand.startsWith(trimmed) && brand.includes(trimmed));
  return [...startsWith, ...includes].slice(0, limit);
}
